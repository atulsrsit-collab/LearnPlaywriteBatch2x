// Integer (decimal)
console.log("Integer:", 42);

// Floating point
console.log("Float:", 3.14);

// Scientific notation
console.log("Scientific:", 1e3);
console.log("Scientific:", 1.5e-2);

// Binary
console.log("Binary 0b1010:", 0b1010);

// Octal
console.log("Octal 0o12:", 0o12);

// Hexadecimal
console.log("Hex 0xFF:", 0xFF);

// BigInt
console.log("BigInt:", 123n);

// Negative
console.log("Negative:", -10);

// Infinity
console.log("Infinity:", Infinity);
console.log("Negative Infinity:", -Infinity);

// NaN
console.log("NaN:", NaN);

// Numeric separator (ES2021)
console.log("Separator 1_000_000:", 1_000_000);
